import { test, expect } from './fixtures'

test('real gateway: stream tools, fold work, resume history, and change reading settings', async ({ page, app }, testInfo) => {
  const composer = page.getByRole('textbox', { name: 'Message ClawCodex' })
  await composer.fill('E2E_INTERIM_TRIGGER inspect the project')
  await composer.press('Enter')
  await expect(page.getByText('All done! Here is the complete summary of what I found.', { exact: true })).toBeVisible({ timeout: 90_000 })
  const groups = page.getByRole('button', { name: /Work details/ })
  await expect(groups.first()).toBeVisible()
  await expect(groups.first()).toHaveAttribute('aria-expanded', 'false')
  await groups.first().click()
  await expect(groups.first()).toHaveAttribute('aria-expanded', 'true')

  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Verbose', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'text font size', exact: true }).fill('20')
  await page.getByRole('spinbutton', { name: 'code font size', exact: true }).fill('15')
  await page.getByRole('button', { name: 'Close settings' }).click()
  await expect(groups).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--cc-text-size'))).toBe('20px')
  await page.screenshot({ path: testInfo.outputPath('conversation.png') })

  await page.reload()
  await expect(page.getByText('All done! Here is the complete summary of what I found.', { exact: true })).toBeVisible()
  await expect(groups).toHaveCount(0)
  await expect(page).toHaveTitle(/ClawCodex/)
  expect(app.url).toContain('127.0.0.1')
})

test('real gateway: model search selects a provider/model and keeps the menu in a narrow viewport', async ({ page, app }) => {
  await page.getByRole('button', { name: /^Model:/ }).click()
  const search = page.getByRole('combobox', { name: 'Search models' })
  await search.fill('v4pro')
  await expect(page.getByRole('menuitem', { name: 'deepseek-v4-pro', exact: true })).toBeVisible()
  await search.press('Enter')
  await expect(page.getByRole('button', { name: 'Model: deepseek:deepseek-v4-pro', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Message ClawCodex' }).fill('Hello from the selected model')
  await page.getByRole('textbox', { name: 'Message ClawCodex' }).press('Enter')
  await expect(page.getByText('Hello from the mock inference server! The full boot chain is working.', { exact: true })).toBeVisible({ timeout: 90_000 })
  await page.setViewportSize({ width: 620, height: 800 })
  await page.getByRole('button', { name: /^Model:/ }).click()
  await expect(search).toBeFocused()
  const bounds = await page.getByRole('menu').boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(620)
  await search.fill('no-such-model')
  await expect(page.getByText('No matching models.')).toBeVisible()
  await search.press('Escape')
  await expect(search).toHaveCount(0)
  expect(app.workspace).toContain('project')
})
