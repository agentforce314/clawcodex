import { test, expect } from './fixtures'

test('real gateway: document metadata and per-tab zoom, source switching, and image fit', async ({ page, app }, testInfo) => {
  const composer = page.getByRole('textbox', { name: 'Message ClawCodex' })
  await composer.fill('Open the workspace')
  await composer.press('Enter')
  await expect(page.getByText('Hello from the mock inference server! The full boot chain is working.', { exact: true })).toBeVisible({ timeout: 90_000 })
  await page.getByRole('button', { name: 'Open workspace in Files' }).click()
  await page.getByRole('button', { name: 'README.md', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Preview body' })).toBeVisible()
  await expect(page.getByLabel('Document properties').getByText('Preview document')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('document-preview.png') })
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(page.getByLabel('Preview zoom level')).toHaveValue('1.25')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'example.txt', exact: true }).click()
  await expect(page.getByText('A file from the real workspace.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Preview zoom level')).toHaveValue('1')
  await page.getByRole('tab', { name: 'README.md', exact: true }).click()
  await expect(page.getByLabel('Preview zoom level')).toHaveValue('1.25')
  await page.getByRole('button', { name: 'Viewer', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Plain text', exact: true }).click()
  await expect(page.locator('[data-preview-line="2"]')).toContainText('title: Preview document')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'preview.svg', exact: true }).click()
  const image = page.getByRole('img', { name: 'Preview of preview.svg' })
  await expect(image).toBeVisible()
  await expect(page.getByLabel('Preview zoom level')).toHaveValue('fit')
  expect((await image.boundingBox())!.width).toBeLessThan(1000)
  await page.getByLabel('Preview zoom level').selectOption('1')
  await expect.poll(async () => (await image.boundingBox())!.width).toBe(2000)
  await page.getByLabel('Preview zoom level').selectOption('fit')
  await page.screenshot({ path: testInfo.outputPath('image-file-preview.png') })
  expect(app.workspace).toContain('project')
})

test('real gateway: Markdown images expand, fit, close with Escape, and preview on hover', async ({ page, app }, testInfo) => {
  await page.getByRole('textbox', { name: 'Message ClawCodex' }).fill('E2E_IMAGE_TRIGGER show the image')
  await page.getByRole('textbox', { name: 'Message ClawCodex' }).press('Enter')
  const thumbnail = page.getByRole('button', { name: 'Expand image: Workspace image' })
  await expect(thumbnail).toBeVisible({ timeout: 90_000 })
  await thumbnail.click()
  const dialog = page.getByRole('dialog', { name: 'Image preview: Workspace image' })
  await expect(dialog).toBeVisible()
  await page.getByRole('button', { name: 'Actual size', exact: true }).click()
  await expect.poll(async () => (await dialog.getByRole('img').boundingBox())!.width).toBe(2000)
  await page.getByRole('button', { name: 'Fit image', exact: true }).click()
  expect((await dialog.getByRole('img').boundingBox())!.width).toBeLessThan(1440)
  await page.screenshot({ path: testInfo.outputPath('expanded-image.png') })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(thumbnail).toBeFocused()
  await page.getByRole('link', { name: 'Inspect linked image' }).hover()
  await expect(page.getByRole('img', { name: 'Linked image preview' })).toBeVisible()
  expect(app.received.join('')).toContain('E2E_IMAGE_TRIGGER')
})
